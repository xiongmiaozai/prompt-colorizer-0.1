/**
 * 渲染 Mac 风格卡片容器
 */
export function renderCard(
  parent: HTMLElement,
  title: string,
  desc: string,
  iconKey: string,
  contentBuilder: (card: HTMLElement) => void
): void {
  const card = parent.createDiv({ cls: 'pc-setting-card' });

  // 卡片标题行 — 含图标
  const titleRow = card.createDiv({ cls: 'pc-setting-card-title' });
  if (CARD_ICONS[iconKey]) {
    const iconWrap = titleRow.createSpan({ cls: 'pc-setting-card-title-icon' });
    iconWrap.innerHTML = CARD_ICONS[iconKey];
  }
  titleRow.createSpan({ text: title });

  // 卡片描述
  if (desc) {
    card.createDiv({
      cls: 'pc-setting-card-desc',
      text: desc,
    });
  }

  // 卡片内容
  contentBuilder(card);
}